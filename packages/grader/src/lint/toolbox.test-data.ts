/** Everything up to and including the given sessions (a crude stand-in for the legal-order rule). */
export function unlockedAt(...ids: string[]): Set<ToolEntry["id"]> {
  const want = new Set(ids);
  return new Set(TOOLBOX.filter((e) => want.has(e.unlock.at as string)).map((e) => e.id));
}

export const ALL_UNLOCKED: ReadonlySet<ToolEntry["id"]> = new Set(TOOLBOX.map((e) => e.id));
