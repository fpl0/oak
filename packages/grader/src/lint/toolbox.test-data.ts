// A slice of the unlock table of contracts §3.2, written the way content/toolbox.ts writes it, for the
// lint's tests (the real table is content's). Not a test file.
import type { SessionId, ToolEntry, ToolKind } from "@oak/content-kit";

function t(id: string, kind: ToolKind, code: string, at: string, matches?: string[]): ToolEntry {
  return {
    id: id as ToolEntry["id"],
    kind,
    code,
    unlock: { at: at as SessionId, when: "complete" },
    concept: "test",
    catalog: { signature: code, meaning: "test", demo: 'setcpm(120/4)\n\ndrums: s("bd")' },
    ...(matches && { matches }),
  };
}

