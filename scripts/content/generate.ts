/** Every ID the sources declare, by kind (the input of ids.ts and the ledger). */
export function collectIds(lessons: readonly LoadedLesson[]): Record<string, string[]> {
  const g = courseGraph();
  const nodes = [...g.nodes.values()];
  const exercises: string[] = [];
  const examples: string[] = [];
  const steps: string[] = [];
  for (const l of lessons.filter((x) => !x.sample)) {
    for (const s of l.def.steps) {
      steps.push(`${l.def.id}/${s.id}`);
      if (s.example) examples.push(`${l.def.id}@${s.example.id}`);
      if (s.exercise) for (const e of flattenExercise(s.exercise)) exercises.push(`${l.def.id}/${e.id}`);
    }
  }
  const byKind: Record<string, string[]> = {
    unit: R.syllabus.units.map((u) => u.id),
    track: R.syllabus.tracks.map((t) => t.id),
    lesson: nodes.filter((n) => n.kind === "lesson").map((n) => n.id),
    checkpoint: R.checkpoints.map((c) => c.id),
    capstone: R.capstones.map((c) => c.id),
    capstoneSession: R.capstones.flatMap((c) => c.sessionDefs.map((s) => s.id)),
    gymSession: R.syllabus.defaultOrder.filter((s) => s.startsWith("GYM.")),
    skill: R.skills.map((s) => s.id),
    family: R.families.map((f) => f.id),
    deck: R.decks.map((d) => d.id),
    fact: R.decks.flatMap((d) => d.cards.map((c) => c.id)),
    tool: R.toolbox.filter((t) => t.id.startsWith("tb.")).map((t) => t.id),
    sound: R.toolbox.filter((t) => t.id.startsWith("snd.")).map((t) => t.id),
    scale: R.toolbox.filter((t) => t.id.startsWith("scale.")).map((t) => t.id),
    chordFamily: R.toolbox.filter((t) => t.id.startsWith("chord.")).map((t) => t.id),
    canDo: R.candos.map((c) => c.id),
    milestone: R.milestones.map((m) => m.id),
    term: R.terms.map((t) => t.id),
    song: R.repertoire.map((s) => s.id),
    flavour: R.flavours.map((f) => f.id),
    band: R.bands.map((b) => b.id),
    unitSong: R.unitSongs.map((s) => s.id),
    step: steps,
    exercise: exercises,
    example: examples,
  };
  for (const k of Object.keys(byKind)) byKind[k] = [...new Set(byKind[k])].sort();
  return byKind;
}

