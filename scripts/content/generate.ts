export function idsModule(byKind: Record<string, string[]>): string {
  const lines = [
    "// GENERATED by scripts/content/build.ts from the content sources. Do not edit.",
    "// One `as const` array, one union type and one guard per ID kind (contracts §1.1 rule 2).",
    "",
  ];
  for (const [kind, list] of Object.entries(byKind)) {
    const T = TYPE_NAMES[kind] as string;
    const C = `${kind.replace(/[A-Z]/g, (c) => `_${c}`).toUpperCase()}_IDS`;
    lines.push(`export const ${C} = ${JSON.stringify(list)} as const;`);
    lines.push(`export type ${T} = (typeof ${C})[number];`);
    lines.push(`const ${kind}Set: ReadonlySet<string> = new Set(${C});`);
    lines.push(
      `export const is${T} = (id: unknown): id is ${T} => typeof id === "string" && ${kind}Set.has(id);`,
    );
    lines.push("");
  }
  lines.push(`export type SessionId = LessonId | CheckpointId | CapstoneSessionId | GymSessionId;`);
  return `${lines.join("\n")}\n`;
}

/** Updates the ledger: new IDs are added; a locked ID missing from the sources is an error unless retired. */
/**
 * Units whose lessons have shipped to the learner. Their step, exercise and example IDs join the ledger
 * (contracts §1.1 rule 4, §11.7 rule 1: attempts and step state are keyed by them, so they never change
 * again). Lessons of later units are still being written, and their authors may rename those IDs freely
 * until the unit is added here.
 */
export const RELEASED_UNITS: readonly string[] = [
  ...["U00", "U01", "U02", "U03", "U04", "U05", "U06", "U07"],
  // Wave 5: U08–U11 and the side lessons A1.L01–L04.
  ...["U08", "U09", "U10", "U11", "A1"],
  // Wave 6, the end of the core: U12–U17 (released in the Wave 6 content integration).
  ...["U12", "U13", "U14", "U15", "U16", "U17"],
  // Wave 7, the advanced tracks (released in the Wave 7 content integration): J1–J5, R1–R3, A2 (A1.L05–L07 are A1's,
  // released with it) and the track checkpoints J.CP1, J.CP2, R.CP, A.CP (their items are scoped "J", "R", "A").
  ...["J1", "J2", "J3", "J4", "J5", "R1", "R2", "R3", "A2", "J", "R", "A"],
];
const LESSON_SCOPED = ["step", "exercise", "example"];
/** The unit of a lesson-scoped ID: "U08" of "U08.L01/S1", "A1" of "A1.L02@hook". */
const released = (id: string) => RELEASED_UNITS.includes(id.split(".")[0] as string);

export function updateLock(
  previous: LockEntry[],
  byKind: Record<string, string[]>,
): { lock: LockEntry[]; errors: string[] } {
  const ledgerKinds = Object.keys(byKind).filter((k) => k !== "track");
  const live = new Map<string, string>();
  for (const k of ledgerKinds)
    for (const id of byKind[k] ?? []) if (!LESSON_SCOPED.includes(k) || released(id)) live.set(id, k);
  const errors: string[] = [];
  const out = new Map<string, LockEntry>(previous.map((e) => [e.id, e]));
  for (const e of previous)
    if (!e.retiredAt && !live.has(e.id))
      errors.push(
        `ID "${e.id}" (${e.kind}) is in content/ids.lock.json but no longer in the sources: retire it, never rename it`,
      );
  for (const [id, kind] of live) if (!out.has(id)) out.set(id, { id, kind });
  return {
    lock: [...out.values()].sort((a, b) =>
      a.kind === b.kind ? a.id.localeCompare(b.id) : a.kind.localeCompare(b.kind),
    ),
    errors,
  };
}

function earStagesOf(lesson: string): string[] {
  const fams = new Set(R.families.filter((f) => f.unlock.lesson === lesson).map((f) => f.id as string));
  return Object.entries(R.earStages)
    .filter(([, list]) => list.some((f) => fams.has(f)))
    .map(([stage]) => stage);
}

function courseIndex(lessons: readonly LoadedLesson[]) {
  const g = courseGraph();
  const order = R.syllabus.defaultOrder as readonly string[];
  const authored = new Map(lessons.filter((l) => !l.sample).map((l) => [l.def.id as string, l.def]));
  const meta = new Map(R.syllabus.units.flatMap((u) => u.lessons.map((l) => [l.id as string, l] as const)));
  const toolsAt = new Map<string, string[]>();
  for (const t of R.toolbox)
    for (const s of Array.isArray(t.unlock.at) ? t.unlock.at : [t.unlock.at])
      toolsAt.set(s, [...(toolsAt.get(s) ?? []), t.id]);
  const sessions = [...g.nodes.values()]
    .map((n) => {
      const m = meta.get(n.id);
      return {
        id: n.id,
        kind: n.kind,
        track: n.track,
        ...(n.unit ? { unit: n.unit } : {}),
        title: n.title,
        objective: n.objective,
        minutes: SESSION_MINUTES[n.kind],
        ...(m ? { introduces: m.introduces, practises: m.practises, earStages: earStagesOf(n.id) } : {}),
        ...(m?.optional ? { optional: true } : {}),
        families: R.families.filter((f) => f.unlock.lesson === n.id).map((f) => f.id),
        unlocks: (toolsAt.get(n.id) ?? []).sort(),
        requires: [...n.requires].sort(),
        defaultOrder: order.indexOf(n.id) + 1 || null,
        authored: authored.has(n.id),
        ...(authored.get(n.id) ? { version: authored.get(n.id)?.version } : {}),
      };
    })
    .sort((a, b) => (a.defaultOrder ?? 1e9) - (b.defaultOrder ?? 1e9) || a.id.localeCompare(b.id));
  return {
    units: R.syllabus.units.map((u) => ({
      id: u.id,
      title: u.title,
      track: u.track,
      ...(u.checkpoint ? { checkpoint: u.checkpoint } : {}),
      lessons: u.lessons.map((l) => l.id),
    })),
    tracks: R.syllabus.tracks,
    trackGates: R.syllabus.trackGates,
    sessions,
  };
}

function skillGraph() {
  const layer = new Map<string, number>();
  const byId = new Map(R.skills.map((s) => [s.id as string, s]));
  const depth = (id: string, seen = new Set<string>()): number => {
    if (layer.has(id)) return layer.get(id) as number;
    if (seen.has(id)) return 0;
    seen.add(id);
    const d = Math.max(-1, ...(byId.get(id)?.prerequisites ?? []).map((p) => depth(p, seen))) + 1;
    layer.set(id, d);
    return d;
  };
  const regions = [...new Set(R.skills.map((s) => s.region))];
  const slot = new Map<string, number>();
  const nodes = R.skills.map((s) => {
    const y = depth(s.id);
    const key = `${s.region}:${y}`;
    const x = regions.indexOf(s.region) * 10 + (slot.get(key) ?? 0);
    slot.set(key, (slot.get(key) ?? 0) + 1);
    return {
      id: s.id,
      name: s.name,
      region: s.region,
      category: s.category,
      kind: s.kind,
      introducedBy: s.introducedBy,
      checkpoint: s.checkpoint ?? null,
      x,
      y,
    };
  });
  const edges = R.skills.flatMap((s) =>
    s.prerequisites.map((p) => ({ from: p, to: s.id, crossRegion: byId.get(p)?.region !== s.region })),
  );
  return { nodes, edges };
}

function codeStringsOf(l: LoadedLesson) {
  const out: { ref: string; code: string; bars: number; kind: string }[] = [];
  const add = (ref: string, code: string, bars: number, kind: string) => out.push({ ref, code, bars, kind });
  for (const s of l.def.steps) {
    if (s.example)
      add(
        `${l.def.id}@${s.example.id}`,
        s.example.code,
        s.example.bars,
        s.example.preview ? "example-preview" : "example",
      );
    if (!s.exercise) continue;
    for (const e of flattenExercise(s.exercise))
      for (const c of exerciseCode(e))
        add(`${l.def.id}/${e.id}#${c.what}`, c.code, c.bars, c.what.split(":")[0] as string);
  }
  return out;
}

/** Every code string an exercise carries: starter, solutions, stimulus, items, test responses. */
export function exerciseCode(e: Exercise): { what: string; code: string; bars: number }[] {
  const out: { what: string; code: string; bars: number }[] = [];
  const bars =
    "reference" in e && e.reference
      ? e.reference.bars
      : "bars" in e && typeof e.bars === "number"
        ? e.bars
        : 1;
  if ("code" in e && typeof e.code === "object" && e.code)
    out.push({ what: "starter", code: stripMarkers(e.code.starter).code, bars });
  if ("code" in e && typeof e.code === "string") out.push({ what: "code", code: e.code, bars });
  if ("reference" in e && e.reference)
    for (const [i, c] of e.reference.solutions.entries()) out.push({ what: `solution:${i}`, code: c, bars });
  if (e.kind === "transcribe-step" && e.grading.mode === "auto")
    for (const [i, c] of e.grading.reference.solutions.entries())
      out.push({ what: `solution:${i}`, code: c, bars: e.grading.reference.bars });
  // Wave 4: the rhythm skeleton a transcription step gives the learner is code they hear and see.
  if (e.kind === "transcribe-step" && e.given?.rhythmSkeleton)
    out.push({ what: "given", code: e.given.rhythmSkeleton, bars: e.bars[1] - e.bars[0] || 1 });
  if ("stimulus" in e && e.stimulus && e.stimulus.src === "code")
    out.push({ what: "stimulus", code: e.stimulus.code, bars: e.stimulus.bars });
  if (e.kind === "listen")
    for (const [i, it] of e.items.entries()) out.push({ what: `item:${i}`, code: it.code, bars: it.bars });
  if (e.kind === "staff-read") out.push({ what: "source", code: e.source, bars: e.bars });
  if (e.kind === "parsons")
    for (const b of e.blocks)
      if (b.audition) out.push({ what: `audition:${b.id}`, code: b.audition, bars: 1 });
  for (const t of e.tests)
    if ("code" in t.response) out.push({ what: `test:${t.name}`, code: t.response.code, bars });
  return out;
}

const SOUND_RE = /\.?(?:s|sound)\(\s*"([^"]+)"/g;
function soundsOf(codes: string[]) {
  const s = new Set<string>();
  const banks = new Set<string>();
  for (const c of codes) {
    for (const m of c.matchAll(SOUND_RE))
      for (const w of (m[1] as string).match(/[a-z][a-z0-9_]*/gi) ?? []) s.add(w);
    for (const m of c.matchAll(/\.bank\(\s*"([^"]+)"/g)) banks.add(m[1] as string);
  }
  return { s: [...s].sort(), banks: [...banks].sort() };
}

function syllabusMarkdown(): string {
  const out = [
    "# Oak syllabus",
    "",
    "One cycle is one bar. Lessons in default order; tools unlock where listed.",
    "",
  ];
  const unlockAt = new Map<string, string[]>();
  for (const t of R.toolbox)
    for (const s of Array.isArray(t.unlock.at) ? t.unlock.at : [t.unlock.at])
      unlockAt.set(s, [...(unlockAt.get(s) ?? []), t.id]);
  for (const u of R.syllabus.units) {
    out.push(`## ${u.id} ${u.title}`, "");
    for (const l of u.lessons) {
      const tools = unlockAt.get(l.id);
      out.push(
        `- ${l.id} ${l.title}: ${l.objective}${l.introduces.length ? ` Introduces ${l.introduces.join(" ")}.` : ""}${tools ? ` Unlocks ${tools.join(" ")}.` : ""}`,
      );
    }
    out.push("");
  }
  return out.join("\n");
}

/** Runs the whole build into `outDir` (default content/.generated). */
export async function generate(
  opts: { root?: string; outDir?: string; lockFile?: string; writeLock?: boolean } = {},
): Promise<BuildResult> {
  const root = opts.root ?? CONTENT_ROOT;
  const outDir = opts.outDir ?? join(root, ".generated");
  const lockFile = opts.lockFile ?? join(root, "ids.lock.json");
  const errors: string[] = [];
  const { lessons, errors: loadErrors } = await loadLessons(root);
  for (const e of loadErrors) errors.push(`${e.file}: ${e.error}`);

  const sources = contentSourceFiles(root);
  const contentVersion = sha(
    sources.map((f) => `${relative(root, f)}\n${readFileSync(f, "utf8")}`).join("\n\0\n"),
  );
  const byKind = collectIds(lessons);
  const previous = existsSync(lockFile)
    ? (JSON.parse(readFileSync(lockFile, "utf8")) as { ids: LockEntry[] }).ids
    : [];
  const { lock, errors: lockErrors } = updateLock(previous, byKind);
  errors.push(...lockErrors);

  const g = courseGraph();
  const order = R.syllabus.defaultOrder as readonly SessionId[];
  const files: Record<string, string> = {};
  const toolTitle = (t: ToolEntry) => {
    const site = firstSite(t, order);
    return g.nodes.get(site)?.title ?? site;
  };
  files["ids.ts"] = idsModule(byKind);
  files["course-index.json"] = json(courseIndex(lessons));
  files["skill-graph.json"] = json(skillGraph());
  files["toolbox.json"] = json(R.toolbox.map((t) => ({ ...t, unlockTitle: toolTitle(t) })));
  files["catalog.json"] = json(
    R.catalog.map((f) => {
      const t = R.toolbox.find((x) => x.id === f.tool);
      return { ...f, unlock: t ? t.unlock : null, unlockTitle: t ? toolTitle(t) : null };
    }),
  );
  const authored = lessons.filter((l) => !l.sample).sort((a, b) => a.def.id.localeCompare(b.def.id));
  files["lessons.json"] = json(
    lessons
      .map((l) => ({
        id: l.def.id,
        sample: l.sample,
        version: l.def.version,
        // Contracts §11.7 rule 9: the hash `lessons.complete` records as `contentHash`. It covers the
        // lesson's own two source files only, so editing another lesson never changes it.
        hash: sha(`${readFileSync(l.file, "utf8")}\n\0\n${l.mdxSource ?? ""}`).slice(0, 16),
        file: relative(root, l.file),
        mdx: l.mdx ? relative(root, l.mdx) : null,
        steps: l.def.steps.map((s) => ({
          id: s.id,
          kind: s.kind,
          minutes: s.minutes,
          graded: Boolean(s.graded),
          optional: Boolean(s.optional),
          exercise: s.exercise ? flattenExercise(s.exercise).map((e) => `${e.kind}:${e.id}`) : [],
          example: s.example?.id ?? null,
        })),
        budget: lessonBudget(l.def),
        wrapAt: l.def.wrapAt,
      }))
      .sort((a, b) => a.id.localeCompare(b.id)),
  );
  const examples = authored.flatMap((l) =>
    codeStringsOf(l).map((c) => ({
      ...c,
      hash: sha(c.code).slice(0, 16),
      key: l.def.key,
      meter: l.def.meter,
      bpm: l.def.bpm,
    })),
  );
  files["examples.json"] = json(examples);
  files["sounds-used.json"] = json(
    Object.fromEntries(authored.map((l) => [l.def.id, soundsOf(codeStringsOf(l).map((c) => c.code))])),
  );
  for (const l of lessons) {
    if (!l.mdxSource) continue;
    const parsed = parseMdx(l.mdxSource);
    const titles = Object.fromEntries((l.def as LessonDef).steps.map((s) => [s.id, s.title]));
    files[`lesson-text/${l.def.id}.json`] = json({
      id: l.def.id,
      title: l.def.title,
      objective: l.def.objective,
      steps: parsed.steps.map((id) => ({ id, title: titles[id] ?? "", text: parsed.text[id] ?? "" })),
    });
  }
  const unlockOf = (tool: string) => {
    const t = R.toolbox.find((x) => x.id === tool);
    return t ? (Array.isArray(t.unlock.at) ? t.unlock.at.join(" or ") : t.unlock.at) : "never";
  };
  files["tutor/syllabus.md"] = `${syllabusMarkdown()}\n`;
  files["tutor/catalog.md"] = `${catalogMarkdown(unlockOf)}\n`;
  files["index.json"] = json({
    contentVersion,
    tutorPrefix: {
      syllabus: sha(files["tutor/syllabus.md"]).slice(0, 16),
      catalog: sha(files["tutor/catalog.md"]).slice(0, 16),
    },
    counts: Object.fromEntries(Object.entries(byKind).map(([k, v]) => [k, v.length])),
    units: R.syllabus.units.map((u) => ({
      id: u.id,
      title: u.title,
      track: u.track,
      lessons: u.lessons.map((l) => ({
        id: l.id,
        title: l.title,
        objective: l.objective,
        authored: authored.some((a) => a.def.id === l.id),
      })),
    })),
    checkpoints: R.checkpoints,
    capstones: R.capstones.map((c) => ({
      id: c.id,
      title: c.title,
      kind: c.kind,
      sessions: c.sessionDefs.map((s) => s.id),
      opensAfter: c.opensAfter,
    })),
    defaultOrder: R.syllabus.defaultOrder,
  });

  writeTree(outDir, files);
  if (opts.writeLock !== false && lockErrors.length === 0)
    atomicWrite(lockFile, json({ version: 1, ids: lock }));
  return { outDir, files: Object.keys(files).sort(), contentVersion, errors, lock };
}

// --- writing ------------------------------------------------------------------------------------
// Several authors run `content:build` (and the dev server's `--watch`) at the same time, and the app,
// the server and the tutor read content/.generated while they do. So the output directory is never
// emptied: every file is written to a temporary sibling and renamed over the old one (rename is atomic
// on one file system), unchanged files are not touched (no spurious watcher events), and files the build
// no longer produces are removed only after the new ones are in place. Two concurrent builds over the
// same sources write byte-identical files, so their interleaving cannot corrupt anything.

let tmpCounter = 0;
/** Writes `body` to `file` atomically; skips the write when the content is already identical. */
export function atomicWrite(file: string, body: string): boolean {
  if (existsSync(file) && readFileSync(file, "utf8") === body) return false;
  mkdirSync(dirname(file), { recursive: true });
  const tmp = join(dirname(file), `.${file.split(/[\\/]/).pop()}.tmp-${process.pid}-${tmpCounter++}`);
  writeFileSync(tmp, body);
  try {
    renameSync(tmp, file);
  } catch (e) {
    rmSync(tmp, { force: true });
    throw e;
  }
  return true;
}

function listFiles(dir: string, base = dir, out: string[] = []): string[] {
  if (!existsSync(dir)) return out;
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    let dirent: ReturnType<typeof statSync>;
    try {
      dirent = statSync(p);
    } catch {
      continue; // renamed or removed by a concurrent build between readdir and stat
    }
    if (dirent.isDirectory()) listFiles(p, base, out);
    else out.push(relative(base, p).split(/[\\/]/).join("/"));
  }
  return out;
}

/** Makes `outDir` hold exactly `files`, without ever leaving a file missing or half-written. */
export function writeTree(outDir: string, files: Record<string, string>): void {
  for (const [name, body] of Object.entries(files)) atomicWrite(join(outDir, name), body);
  for (const name of listFiles(outDir)) {
    if (name in files) continue;
    // Another build's temporary file: leave it to that build.
    if (/(^|\/)\.[^/]+\.tmp-\d+-\d+$/.test(name)) continue;
    rmSync(join(outDir, name), { force: true });
  }
}
